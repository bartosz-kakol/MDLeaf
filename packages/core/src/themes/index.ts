import { CSS_CONTRACT_VERSION, cssClassNames, cssCustomProperties, generateRootDefaults } from '../css-contract/contract.ts';

export interface ThemePreset {
  id: `preset:${string}`;
  name: string;
  file: string;
  description: string;
}

export const THEME_PRESETS: readonly ThemePreset[] = [
  { id: 'preset:classic', name: 'Classic', file: 'classic.css', description: 'Word-like serif with thin table rules.' },
  { id: 'preset:modern', name: 'Modern', file: 'modern.css', description: 'Inter with a larger heading scale and a green accent.' },
  { id: 'preset:technical', name: 'Technical', file: 'technical.css', description: 'Compact, with shaded code and zebra tables.' },
];

export function isPresetThemeId(id: string): boolean {
  return id.startsWith('preset:');
}

export function findPreset(id: string): ThemePreset | undefined {
  return THEME_PRESETS.find((p) => p.id === id);
}

export const DOCS_CONTRACT_PATH = '/styling/css-contract/';

const LEADER_REPEAT = 160;

/** Builds base.css from the contract defaults and the hand-written structure. */
export function generateBaseCss(structureCss: string): string {
  const run = Array.from({ length: LEADER_REPEAT }, () => 'var(--mdl-toc-leader)').join(' ');
  const structure = structureCss.replace('var(--mdl-toc-leader-run)', run);
  return `/*
 * MDLeaf base stylesheet — CSS contract v${CSS_CONTRACT_VERSION}.
 * GENERATED by packages/core/scripts/gen-contract.ts from css-contract/contract.ts
 * and themes/base.structure.css. Do not edit by hand.
 */

${generateRootDefaults()}
${structure}`;
}

/** Reads the custom properties a stylesheet sets on `:root`. */
export function parseRootProperties(css: string): Record<string, string> {
  const out: Record<string, string> = {};
  const noComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const block of noComments.matchAll(/:root\s*\{([^}]*)\}/g)) {
    for (const decl of block[1].split(';')) {
      const m = /^\s*(--[\w-]+)\s*:\s*([\s\S]+?)\s*$/.exec(decl);
      if (m) out[m[1]] = m[2];
    }
  }
  return out;
}

/**
 * Generates starter.css: every writable custom property with its default
 * (or the value from `overrides`, e.g. a preset's values) and commented-out
 * examples for the structural classes.
 */
export function generateStarterCss(options: { docsUrl?: string; overrides?: Record<string, string>; title?: string } = {}): string {
  const docs = `${(options.docsUrl ?? 'https://mdleaf-docs.pages.dev').replace(/\/$/, '')}${DOCS_CONTRACT_PATH}`;
  const groups = new Map<string, typeof cssCustomProperties>();
  for (const p of cssCustomProperties) {
    if (p.readOnly) continue;
    const list = groups.get(p.group) ?? [];
    list.push(p);
    groups.set(p.group, list);
  }
  const width = Math.max(...cssCustomProperties.map((p) => p.name.length));
  let root = ':root {\n';
  for (const [group, props] of groups) {
    root += `  /* ${group} */\n`;
    for (const p of props) {
      const value = options.overrides?.[p.name] ?? p.default;
      root += `  ${`${p.name}:`.padEnd(width + 1)} ${value}; /* ${p.description} */\n`;
    }
    root += '\n';
  }
  root = `${root.trimEnd()}\n}\n`;

  const readOnly = cssCustomProperties
    .filter((p) => p.readOnly)
    .map((p) => p.name)
    .join(', ');

  const examples = cssClassNames.map((c) => `/* ${c.selector} — ${c.description} (${c.modes.join(', ')}) */`).join('\n');

  return `/*
 * ${options.title ?? 'MDLeaf starter stylesheet'} — CSS contract v${CSS_CONTRACT_VERSION}
 * Reference: ${docs}
 *
 * Rules:
 *  1. Set the custom properties below on :root. Remove the ones you do not change.
 *  2. Do not set the read-only layout properties (${readOnly});
 *     MDLeaf sets them from the profile. Page size and margins always come from the profile.
 *  3. For a theme that works offline as an uploaded file, embed fonts and images as data: URLs.
 */

${root}
/*
 * Structural classes you can style (uncomment and edit the examples below):
 *
${examples
  .split('\n')
  .map((l) => ` * ${l.replace(/\/\*|\*\//g, '').trim()}`)
  .join('\n')}
 */

/* Headings
.mdl-document h1 { letter-spacing: -0.01em; }
.mdl-document h2 { border-bottom: 1px solid var(--mdl-color-border); padding-bottom: 0.2em; }
*/

/* Start every level-1 heading on a new page (page view and PDF)
.mdl-document h1 { break-before: page; }
*/

/* Running headers and footers
.mdl-page-header { border-bottom: 0.5pt solid var(--mdl-color-border); }
.mdl-page-footer .mdl-slot--center { font-variant-numeric: tabular-nums; }
.mdl-page--first .mdl-page-header { display: none; }
*/

/* Table of contents
.mdl-toc-title { text-transform: uppercase; letter-spacing: 0.08em; }
.mdl-toc-item--level-1 { font-weight: 600; margin-top: 0.5em; }
.mdl-toc-page { color: var(--mdl-color-muted); }
*/

/* Images
.mdl-img-block { margin: 1em 0; }
.mdl-img[data-align="center"] { box-shadow: 0 1px 3px rgb(0 0 0 / 0.2); }
*/

/* Keep-together: never split blockquotes across pages
.mdl-document blockquote { break-inside: avoid; }
*/

/* Pages
.mdl-page { background: #fffdf8; }
*/
`;
}

/**
 * Rewrites relative `url(...)` and `@import "…"` references to absolute URLs
 * resolved against `baseUrl`.
 */
export function absolutizeCssUrls(css: string, baseUrl: string): string {
  const resolve = (u: string) => {
    const trimmed = u.trim();
    if (!trimmed || /^(?:[a-z][a-z0-9+.-]*:|#|\/\/)/i.test(trimmed)) {
      if (trimmed.startsWith('//')) {
        try {
          return new URL(trimmed, baseUrl).href;
        } catch {
          return trimmed;
        }
      }
      return trimmed;
    }
    try {
      return new URL(trimmed, baseUrl).href;
    } catch {
      return trimmed;
    }
  };
  let out = css.replace(/url\(\s*(?:"([^"]*)"|'([^']*)'|([^)'"\s][^)]*?))\s*\)/gi, (m, dq, sq, bare) => {
    const raw = dq ?? sq ?? bare ?? '';
    const abs = resolve(raw);
    if (abs === raw.trim()) return m;
    const q = dq !== undefined ? '"' : sq !== undefined ? "'" : '';
    return `url(${q}${abs}${q})`;
  });
  out = out.replace(/@import\s+(["'])([^"']*)\1/gi, (m, q, u) => {
    const abs = resolve(u);
    return abs === u.trim() ? m : `@import ${q}${abs}${q}`;
  });
  return out;
}
